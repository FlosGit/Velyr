const STOP = new Set(['a', 'an', 'the', 'to', 'of', 'for', 'in', 'on', 'your',
  'with', 'how', 'what', 'is', 'do', 'does', 'when', 'why', 'from'])

function slugify(s) {
  let slug = s.toLowerCase()
    .replace(/\.js\b/g, 'js')          // next.js -> nextjs, vue.js -> vuejs
    .replace(/\ba\/b\b/g, 'ab')        // "A/B" -> "ab" (don't let the 'a' get stripped)
    .replace(/&/g, ' and ')
    .replace(/[''`]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .split(/\s+/)
    .filter((w) => !STOP.has(w))
    .join('-')
  if (slug.length > 60) {
    slug = slug.slice(0, 60)
    slug = slug.slice(0, slug.lastIndexOf('-') >= 0 ? slug.lastIndexOf('-') : 60)
  }
  return slug
}

