// ── assemble + validate ───────────────────────────────────────────────────────
const topics = []
const bySlug = new Map()
const issues = []

function add(slug, title, cluster, status) {
  if (!CLUSTER_SLUGS.includes(cluster)) issues.push(`unknown cluster "${cluster}" for "${title}"`)
  if (slug.length > 60) issues.push(`slug >60 chars (${slug.length}): ${slug}`)
  if (bySlug.has(slug)) issues.push(`duplicate slug "${slug}" — "${title}" vs "${bySlug.get(slug)}"`)
  bySlug.set(slug, title)
  topics.push({ slug, title, cluster, status })
}

for (const [slug, title, cluster] of SEEDS) add(slug, title, cluster, 'published')
for (const cluster of Object.keys(TITLES)) {
  for (const title of TITLES[cluster]) add(slugify(title), title, cluster, 'draft')
}

if (issues.length) {
  console.error('build-topics: validation FAILED:')
  for (const i of [...new Set(issues)]) console.error('  ' + i)
  process.exit(1)
}

// counts per cluster
const counts = {}
for (const t of topics) counts[t.cluster] = (counts[t.cluster] || 0) + 1

writeFileSync(OUT, JSON.stringify(topics, null, 2) + '\n', 'utf8')
console.log(`build-topics: wrote ${topics.length} topics → content/blog-topics.json`)
console.log('per cluster:')
for (const c of CLUSTER_SLUGS) console.log(`  ${String(counts[c] || 0).padStart(3)}  ${c}`)
